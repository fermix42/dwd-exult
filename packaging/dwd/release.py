"""DWD metadata and allowlisted Windows candidate packaging. Python standard library."""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import zipfile
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def optional_policy_module():
    spec = importlib.util.spec_from_file_location('dwd_optional_content', ROOT / 'packaging/dwd/optional_content.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module

def git(*args):
    return subprocess.check_output(['git', '-C', str(ROOT), *args], text=True).strip()

def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding='utf-8') != text:
        path.write_text(text, encoding='utf-8')

def metadata():
    meta = json.loads((ROOT / 'packaging/dwd/version.json').read_text())
    assert re.fullmatch(r'\d+\.\d+\.\d+(?:-(?:rc|alpha|beta)\.\d+)?', meta['version'])
    upstream = meta['upstream_revision']
    assert re.fullmatch(r'[0-9a-f]{40}', upstream)
    if (ROOT / '.git').exists():
        subprocess.run(['git', '-C', str(ROOT), 'merge-base', '--is-ancestor', upstream, 'HEAD'], check=True)
        meta['dwd_revision'] = git('rev-parse', 'HEAD')
        meta['dirty'] = bool(git('status', '--porcelain', '--untracked-files=normal'))
    else:
        provenance = json.loads((ROOT / 'source-provenance.json').read_text())
        assert provenance['version'] == meta['version'] and provenance['upstream_revision'] == upstream
        meta['dwd_revision'] = provenance['dwd_revision']
        manifest = json.loads((ROOT / 'source-manifest.json').read_text())
        meta['dirty'] = any(not (ROOT / name).is_file() or sha(ROOT / name) != digest for name, digest in manifest.items())
    values = {'DWD_VERSION': meta['version'], 'DWD_UPSTREAM_VERSION': meta['upstream_version'],
              'DWD_UPSTREAM_REVISION': upstream, 'DWD_REVISION': meta['dwd_revision'],
              'DWD_SOURCE_URL': meta['source_url']}
    header = '// Generated by packaging/dwd/release.py; do not edit.\n#pragma once\n'
    header += ''.join('#define ' + key + ' ' + json.dumps(value) + '\n' for key, value in values.items())
    header += '#define DWD_FILE_VERSION ' + meta['version'].split('-')[0].replace('.', ',') + ',0\n'
    header += '#define DWD_BUILD_DIRTY ' + str(int(meta['dirty'])) + '\n'
    write(ROOT / 'dwd_version_generated.h', header)
    return meta

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def release_notes(meta):
    text = (ROOT / 'ChangeLog-DWD.txt').read_text(encoding='utf-8')
    marker = 'version: ' + meta['version'] + '\n'
    assert marker in text, 'Missing curated version history'
    return marker + text.split(marker, 1)[1].split('\nversion:', 1)[0]

def copy(source, dest):
    assert source.is_file(), f'Missing required file: {source}'
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, dest)

def installer(stage, meta):
    # Derive the complete upstream installer; retain path setup, downloads,
    # optional mod handling, architecture selection and uninstall behavior.
    text = (ROOT / 'win32/exult_installer.iss').read_text(encoding='utf-8')
    replacements = {
        'AppName=Exult': 'AppId=DWDExult\nAppName=' + meta['name'],
        'AppVerName=Exult 1.13.1git Snapshot': 'AppVerName=' + meta['name'] + ' ' + meta['version'],
        'AppPublisher=The Exult Team': 'AppPublisher=Dark Wraith Dragon (independent Exult fork)',
        'AppPublisherURL=https://exult.info/': 'AppPublisherURL=' + meta['source_url'],
        'AppSupportURL=https://exult.info/': 'AppSupportURL=' + meta['source_url'] + '/issues',
        'AppUpdatesURL=https://exult.info/': 'AppUpdatesURL=' + meta['source_url'] + '/releases',
        'VersionInfoVersion=1.13.1': 'VersionInfoVersion=' + meta['version'].split('-')[0] + '.0',
        'DefaultDirName={code:GetExultInstDir|{autopf}\\Exult}':
            'PrivilegesRequired=lowest\nDefaultDirName={code:GetExultInstDir|{sd}\\Games\\DWDExult}',
        'DefaultGroupName={code:GetExultGroupDir|Exult}': 'DefaultGroupName={code:GetExultGroupDir|DWD Exult}',
        'OutputBaseFilename=Exult': 'OutputBaseFilename=DWD-Exult-' + meta['version'] + '-Setup',
        'Software\\Exult': 'Software\\DWDExult',
        'HKEY_LOCAL_MACHINE': 'HKEY_CURRENT_USER',
        "PackVersionComponents(1,13,1,0)": 'PackVersionComponents(1,0,0,0)',
        'Name: {group}\\Uninstall Exult;': 'Name: {group}\\Uninstall DWD Exult;',
    }
    for before, after in replacements.items():
        assert before in text, f'Upstream installer changed: {before}'
        text = text.replace(before, after)
    text = text.replace("sBGmods := BGPath + '\\mods';", "sBGmods := ExpandConstant('{app}\\mods\\blackgate');")
    text = text.replace("sSImods := SIPath + '\\mods';", "sSImods := ExpandConstant('{app}\\mods\\serpentisle');")
    text = text.replace("Log('SetExultGamePaths failed: '+  IntToStr(ResultCode));", "RaiseException('Could not write DWD configuration in the selected installation directory: '+IntToStr(ResultCode));")
    text = text.replace('if (ResultCode < 0) then begin', 'if (ResultCode <> 0) then begin')
    downloads = json.loads((ROOT / 'packaging/dwd/downloads.json').read_text())
    text = text.replace("https://downloads.sourceforge.net/project/exult/exult-data/exult_audio.zip", downloads['exult_audio.zip']['url'])
    for name in ['Ultima6-1.3.zip', 'Glimmerscape_SI_mod_by_Donfrow.zip']:
        text = text.replace("'" + name + "', ''", "'" + name + "', '" + downloads[name]['sha256'] + "'")
    text = text.replace('Description: "Keyring mod for The Black Gate"', "Description: \"Marzo's Keyring (original) for The Black Gate\"")
    text = text.replace('Description: "SIFixes mod for Serpent Isle"', 'Description: "SI Fixes (original) for Serpent Isle"')
    # Command-line equivalents use the same edit controls/validation as the wizard.
    # They make unattended installs useful without replacing the browse page.
    text = text.replace("  BGPath := '';", "  BGPath := ExpandConstant('{param:BGDIR|}');\n  BGEdit.Text := BGPath;")
    text = text.replace("  SIPath := '';", "  SIPath := ExpandConstant('{param:SIDIR|}');\n  SIEdit.Text := SIPath;")
    text = text.replace("      BGEdit.Text := sBGPath;\n      SIEdit.Text := sSIPath;", "      if BGEdit.Text = '' then BGEdit.Text := sBGPath;\n      if SIEdit.Text = '' then SIEdit.Text := sSIPath;")
    # Silent setup does not visit custom pages. Load/validate their real values
    # at the ready boundary before deciding which requested downloads to fetch.
    ready = "      DownloadPage.Clear;"
    text = text.replace(ready, """      if BGEdit.Text = '' then GetExultGamePaths(ExpandConstant('{app}'), BGPath, SIPath)
      else begin BGPath := BGEdit.Text; SIPath := SIEdit.Text; end;
      iBGVerified := VerifyBGDirectory(BGPath);
      iSIVerified := VerifySIDirectory(SIPath);
""" + ready)
    text = text.replace('  PrevItemAChecked: Boolean;', '  PrevItemAChecked: Boolean;\n  DwdDownloadsReady: Boolean;')
    text = text.replace('          DownloadPage.Download;', '          DownloadPage.Download;\n          DwdDownloadsReady := True;')
    text = text.replace('        BGEdit.Text := sBGPath;', "        if BGEdit.Text = '' then BGEdit.Text := sBGPath;")
    text = text.replace('        SIEdit.Text := sSIPath;', "        if SIEdit.Text = '' then SIEdit.Text := sSIPath;")
    text += r"""
// Preserve the same download page and validation in unattended installations.
function PrepareToInstall(var NeedsRestart: Boolean): String;
var Code: Integer; Output: TExecOutput;
begin
  Result := '';
  if BGEdit.Text <> '' then BGPath := BGEdit.Text;
  if SIEdit.Text <> '' then SIPath := SIEdit.Text;
  if not ExecAndCaptureOutput(sExConfigPath, 'VerifyDwdRoot "'+ExpandConstant('{app}')+'" "'+BGPath+'" "'+SIPath+'"', '', SW_HIDE, ewWaitUntilTerminated, Code, Output) or (Code <> 0) then begin
    Result := 'Choose a separate DWD folder outside the original game directories and keep original assets outside DWD-managed data folders.';
    exit;
  end;
  if WizardSilent and not DwdDownloadsReady then begin
    if not NextButtonClick(wpReady) then
      Result := 'The requested optional DWD downloads could not be prepared.';
  end;
  if (Result = '') and ((WizardIsComponentSelected('downloads\mods\keyring')) or
      (WizardIsComponentSelected('downloads\mods\sfisland')) or
      (WizardIsComponentSelected('downloads\3rdpartymods\ultima6'))) and (iBGVerified <> 1) then
    Result := 'Select valid Black Gate game assets or deselect its optional mods.';
  if (Result = '') and ((WizardIsComponentSelected('downloads\mods\sifixes')) or
      (WizardIsComponentSelected('downloads\3rdpartymods\glimmerscape'))) and (iSIVerified <> 1) then
    Result := 'Select valid Serpent Isle game assets or deselect its optional mods.';
end;
"""
    # Initialize from command line or existing config even when no download step runs.
    text = text.replace("    SetExultGamePaths(ExpandConstant('{app}'), BGPath, SIPath );", """    if BGEdit.Text <> '' then BGPath := BGEdit.Text;
    if SIEdit.Text <> '' then SIPath := SIEdit.Text;
    SetExultGamePaths(ExpandConstant('{app}'), BGPath, SIPath );""")
    extra = '\n'.join('Source: Exult\\' + name + '; DestDir: {app}; Flags: ignoreversion; Components: GPL'
                      for name in ['README-DWD.md', 'ChangeLog-DWD.txt', 'release-metadata.json', 'dependency-sources.json', 'mod-distribution.json', 'INSTALL.txt'])
    extra += '\nSource: Exult\\licenses\\*; DestDir: {app}\\licenses; Flags: ignoreversion recursesubdirs; Components: GPL\n'
    text = text.replace("HKEY_CURRENT_USER, 'Software\\Wine'", "HKEY_LOCAL_MACHINE, 'Software\\Wine'")
    # Track only DWD registry values in Inno's uninstall log; upstream's raw
    # RegWriteStringValue calls otherwise leave a stale installation path behind.
    text = text.replace("    RegWriteStringValue(HKEY_CURRENT_USER, 'Software\\DWDExult', 'Path', ExpandConstant('{app}'));", '')
    text = text.replace("    if WizardIsComponentSelected('Icons') then\n      RegWriteStringValue(HKEY_CURRENT_USER, 'Software\\DWDExult', 'ShellObjectFolder', ExpandConstant('{groupname}'));", '')
    registry = '[Registry]\nRoot: HKCU; Subkey: Software\\DWDExult; ValueType: string; ValueName: Path; ValueData: {app}; Flags: uninsdeletevalue uninsdeletekeyifempty\nRoot: HKCU; Subkey: Software\\DWDExult; ValueType: string; ValueName: ShellObjectFolder; ValueData: {groupname}; Components: Icons; Flags: uninsdeletevalue uninsdeletekeyifempty\n\n'
    text = text.replace('[Icons]', extra + '\n' + registry + '[Icons]')
    text = text.replace('[Run]', 'Name: {group}\\DWD Readme; Filename: {app}\\README-DWD.md; Components: Icons\n\n[Run]')
    text = optional_policy_module().policy(text)
    write(stage / 'dwd_installer.iss', text)
    copy(ROOT / 'win32/archs_include.iss', stage / 'archs_include.iss')

def package(args):
    meta = metadata()
    assert not meta['dirty'], 'Candidate packaging requires a clean committed tree'
    if args.tag:
        assert args.tag == 'dwd-v' + meta['version'], 'Tag/version mismatch'
        assert git('rev-parse', args.tag + '^{commit}') == meta['dwd_revision'], 'Tag/commit mismatch'
    output = Path(args.output).resolve()
    assert not output.exists(), 'Use a fresh output directory'
    assert ROOT not in output.parents or (ROOT / 'release-output') in output.parents, 'Output inside source must be under release-output'
    binary = Path(args.binary_dir).resolve()
    runtime = Path(args.runtime_dir).resolve()
    stage = output / 'installer-input'
    payload = stage / 'Exult'
    exe = binary / 'Exult.exe'
    # Inspect executable strings so stale upstream/preparation binaries cannot be relabeled.
    content = exe.read_bytes()
    for value in [meta['version'], meta['dwd_revision'], meta['upstream_revision']]:
        assert value.encode() in content, 'Executable metadata missing/stale: ' + value
    copy(exe, payload / 'x86_64/Exult.exe')
    # Explicit runtime inventory for the verified MSVC Release/x64 dependency set.
    for name in ['SDL3.dll', 'libfluidsynth-3.dll', 'libpng16.dll', 'mt32emu-2.dll',
                 'ogg.dll', 'vorbis.dll', 'vorbisenc.dll', 'vorbisfile.dll', 'z.dll']:
        copy(runtime / name, payload / 'x86_64' / name)
    for name in ['exult.flx', 'exult_bg.flx', 'exult_si.flx']:
        copy(binary / 'data' / name, payload / 'data' / name)
    docs = {'README': 'README.txt', 'ChangeLog': 'ChangeLog.txt', 'COPYING': 'COPYING.txt',
            'AUTHORS': 'AUTHORS.txt', 'INSTALL': 'INSTALL.txt', 'FAQ': 'FAQ.txt', 'NEWS': 'NEWS.txt',
            'README.windows': 'README.windows.txt', 'docs/ReadMe.html': 'ReadMe.html',
            'docs/faq.html': 'faq.html', 'win32/README-SDL.txt': 'README-SDL.txt',
            'README-DWD.md': 'README-DWD.md', 'ChangeLog-DWD.txt': 'ChangeLog-DWD.txt',
            'data/bg/defaultkeys.txt': 'bgdefaultkeys.txt', 'data/si/defaultkeys.txt': 'sidefaultkeys.txt'}
    copy(ROOT / 'packaging/dwd/mods.json', payload / 'mod-distribution.json')
    for src, dst in docs.items():
        copy(ROOT / src, payload / dst)
    for pattern in ['*.gif', '*.svg', 'docs*.png']:
        for path in (ROOT / 'docs/images').glob(pattern):
            copy(path, payload / 'images' / path.name)
    copy(ROOT / 'audio/midi_drivers/nuked-opl3/LICENSE', payload / 'licenses/NukedOPL3-LICENSE.txt')
    copy(ROOT / 'audio/midi_drivers/nuked-opl3/README.exult', payload / 'licenses/NukedOPL3-NOTICE.txt')
    # Collect dependency notices from the matching vcpkg installation, never player files.
    share = Path(args.dependency_share).resolve()
    for name in ['sdl3', 'fluidsynth', 'libpng', 'libmt32emu', 'libogg', 'libvorbis', 'zlib', 'dirent', 'gcem']:
        copy(share / name / 'copyright', payload / 'licenses' / (name + '-copyright.txt'))
    write(payload / 'release-metadata.json', json.dumps(meta, indent=2) + '\n')
    write(payload / 'Exult Source Code.url', '[InternetShortcut]\nURL=' + meta['source_url'] + '/tree/' + meta['dwd_revision'] + '\n')
    if args.iscc:
        copy(Path(args.iscc).resolve().parent / 'License.txt', payload / 'licenses/InnoSetup-LICENSE.txt')
    if args.installer_tools:
        optional_policy_module().catalog(stage, args.installer_tools)
    installer(stage, meta)
    write(output / 'release-notes.txt', release_notes(meta))
    copy(ROOT / 'packaging/dwd/downloads.json', output / 'optional-downloads.json')
    # A source archive includes only committed files, never ignored runtime data.
    subprocess.run(['git', '-C', str(ROOT), 'archive', '--format=zip', '--prefix=dwd-exult/',
                    '-o', str(output / ('DWD-Exult-' + meta['version'] + '-Source.zip')), 'HEAD'], check=True)
    sources = Path(args.dependency_sources).resolve() if args.dependency_sources else None
    if sources:
        dependency_info = json.loads((sources / 'dependency-sources.json').read_text())
        for component in dependency_info['components'].values():
            assert hashlib.sha512((sources / component['archive']).read_bytes()).hexdigest() == component['source_sha512']
            for dll, expected in component['runtime_sha256'].items():
                assert sha(runtime / dll) == expected, 'Runtime/source mismatch: ' + dll
        sourcezip = output / ('DWD-Exult-' + meta['version'] + '-Source.zip')
        with zipfile.ZipFile(sourcezip, 'a', zipfile.ZIP_DEFLATED) as archive:
            manifest = {i.filename.removeprefix('dwd-exult/'): hashlib.sha256(archive.read(i)).hexdigest()
                        for i in archive.infolist() if not i.is_dir()}
            archive.writestr('dwd-exult/source-manifest.json', json.dumps(manifest, indent=2)+'\n')
            archive.writestr('dwd-exult/source-provenance.json', json.dumps(meta, indent=2)+'\n')
            archive.write(ROOT / 'dwd_version_generated.h', 'dwd-exult/dwd_version_generated.h')
            for path in sorted(sources.rglob('*')):
                if path.is_file(): archive.write(path, 'dwd-exult/dependency-sources/' + path.relative_to(sources).as_posix())
        write(payload / 'dependency-sources.json', json.dumps(dependency_info, indent=2)+'\n')
        write(output / 'dependency-sources.json', json.dumps(dependency_info, indent=2)+'\n')
    if args.installer_tools:
        tools = Path(args.installer_tools)
        copy(tools / 'exconfig.exe', stage / 'exconfig.exe')
    portable = output / ('DWD-Exult-' + meta['version'] + '-Windows-x64.zip')
    with zipfile.ZipFile(portable, 'w', zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(payload.rglob('*')):
            if path.is_file():
                rel = path.relative_to(payload)
                if rel.parts[0] == 'x86_64':
                    rel = Path(*rel.parts[1:])
                archive.write(path, 'DWDExult/' + rel.as_posix())
    blockers = []
    if not sources: blockers.append('Corresponding external dependency sources were not supplied.')
    if args.installer_tools:
        assert args.iscc, 'Specify the Inno Setup 6 compiler'
        subprocess.run([args.iscc, '/DNO_i686=1', '/DNO_ARM64=1', str(stage / 'dwd_installer.iss')], check=True)
        for path in stage.glob('*-Setup.exe'):
            copy(path, output / path.name)
    else:
        blockers.append('Installer NOT BUILT: supply source-built exconfig.exe, Inno Setup 6 (--installer-tools, --iscc).')
    files = {str(p.relative_to(payload)): sha(p) for p in sorted(payload.rglob('*')) if p.is_file()}
    write(output / 'payload-manifest.json', json.dumps(files, indent=2) + '\n')
    write(output / 'validation.json', json.dumps({'metadata': meta, 'payload_files': len(files),
          'blockers': blockers, 'runtime': 'NOT TESTED by packaging script',
          'installer_behavior': 'NOT TESTED', 'dependency_source_compliance':
          'PASS' if sources else 'FAIL: external dependency sources missing'}, indent=2) + '\n')
    write(output / 'SHA256SUMS.txt', ''.join(sha(p) + '  ' + p.name + '\n' for p in sorted(output.iterdir()) if p.is_file() and p.name != 'SHA256SUMS.txt'))
    print(output)
    for blocker in blockers:
        print(blocker)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('metadata')
    build = sub.add_parser('package')
    for flag in ['binary-dir', 'runtime-dir', 'dependency-share', 'output']:
        build.add_argument('--' + flag, required=True)
    for flag in ['tag', 'installer-tools', 'iscc', 'dependency-sources']:
        build.add_argument('--' + flag)
    args = parser.parse_args()
    if args.command == 'metadata':
        print(json.dumps(metadata(), indent=2))
    else:
        package(args)

if __name__ == '__main__':
    main()
