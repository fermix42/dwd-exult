"""Compile the three built-in quiz helpers with the ordinary UCC compiler."""
import argparse
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ucc', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    text = '// Generated by tools/compile_quiz.py; edit data/quiz_{bg,si}.uc.\n#pragma once\n'
    header = Path(args.output).resolve()
    header.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='exult-quiz-', dir=header.parent) as temporary:
        for game in ('bg', 'si'):
            output = Path(temporary) / (game + '.ucb')
            # No symbol table: loading these helpers must not replace mod symbols.
            subprocess.run([args.ucc, '-b', '-o', str(output),
                            str(root / 'data' / ('quiz_' + game + '.uc'))], check=True)
            data = output.read_bytes()
            text += 'static constexpr unsigned char quiz_' + game + '[] = {\n'
            for i in range(0, len(data), 20):
                text += '    ' + ','.join(str(n) for n in data[i:i + 20]) + ',\n'
            text += '};\n'
    # Never publish a partial header. A byte-identical regeneration still marks
    # the output current with respect to its source/compiler dependencies.
    if not header.exists() or header.read_text() != text:
        temporary = header.with_suffix('.tmp')
        temporary.write_text(text)
        temporary.replace(header)
    else:
        header.touch()


if __name__ == '__main__':
    main()
